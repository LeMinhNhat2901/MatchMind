"""Tests for the chat translation layer (fake llm_call, no network)."""
from __future__ import annotations

import json

from matchmind.agent.translation import (
    detect_and_translate_to_english,
    mentioned_player_mismatch,
    translate_from_english,
)


def _fake_llm(response: str):
    def _call(prompt: str, **kwargs) -> tuple[str, int]:
        return response, 10

    return _call


def test_detect_and_translate_vietnamese():
    payload = json.dumps({
        "language": "Vietnamese",
        "is_english": False,
        "english_text": "What should player 10 do?",
    })
    result = detect_and_translate_to_english("cầu thủ 10 nên làm gì?", llm_call=_fake_llm(payload))
    assert result.language == "Vietnamese"
    assert result.is_english is False
    assert result.english_text == "What should player 10 do?"
    assert result.original_text == "cầu thủ 10 nên làm gì?"


def test_detect_and_translate_english_passthrough():
    payload = json.dumps({"language": "English", "is_english": True, "english_text": "What should player 10 do?"})
    result = detect_and_translate_to_english("What should player 10 do?", llm_call=_fake_llm(payload))
    assert result.is_english is True
    assert result.language == "English"


def test_detect_and_translate_empty_text_no_llm_call():
    calls = []

    def _tracking_llm(prompt: str, **kwargs):
        calls.append(prompt)
        return "{}", 0

    result = detect_and_translate_to_english("   ", llm_call=_tracking_llm)
    assert result.english_text == ""
    assert calls == []


def test_detect_and_translate_llm_failure_falls_back_to_english_passthrough():
    def _failing_llm(prompt: str, **kwargs):
        raise RuntimeError("429")

    result = detect_and_translate_to_english("bonjour", llm_call=_failing_llm)
    assert result.english_text == "bonjour"
    assert result.language == "English"
    assert result.is_english is True


def test_detect_and_translate_unparseable_json_falls_back():
    result = detect_and_translate_to_english("hola", llm_call=_fake_llm("not json"))
    assert result.english_text == "hola"
    assert result.is_english is True


def test_translate_from_english_skips_when_already_english():
    calls = []

    def _tracking_llm(prompt: str, **kwargs):
        calls.append(prompt)
        return "should not be called", 0

    result = translate_from_english("Pass to player 8.", "English", llm_call=_tracking_llm)
    assert result == "Pass to player 8."
    assert calls == []


def test_translate_from_english_translates():
    result = translate_from_english(
        "Pass to player 8.", "Vietnamese", llm_call=_fake_llm("Chuyền cho cầu thủ @@0@@.")
    )
    assert result == "Chuyền cho cầu thủ 8."


def test_translate_from_english_protects_player_number_against_mistranslation():
    """Reproduces a real production bug: a translation turned 'Player 11' into
    'Cầu thủ 1', silently misattributing advice to the wrong player. The digit
    must never be regenerated by the translation LLM — only restored by literal
    dict lookup — so even a translator that WOULD mangle a bare digit can't corrupt
    it, because it never sees the digit as translatable text in the first place.
    "Player" itself stays as normal text so it can still be localized naturally.
    """

    def _sloppy_llm(prompt: str, **kwargs):
        assert "Player 11" not in prompt  # digit never exposed raw next to "Player"
        assert "@@0@@" in prompt
        return "Cầu thủ @@0@@ nên di chuyển.", 10

    result = translate_from_english("Player 11 should move.", "Vietnamese", llm_call=_sloppy_llm)
    assert result == "Cầu thủ 11 nên di chuyển."
    assert "Cầu thủ 1 " not in result


def test_translate_from_english_falls_back_to_english_when_placeholder_dropped():
    def _lossy_llm(prompt: str, **kwargs):
        # Simulates a translator that drops the placeholder instead of preserving it.
        return "Cầu thủ nên di chuyển.", 10

    result = translate_from_english("Player 11 should move.", "Vietnamese", llm_call=_lossy_llm)
    assert result == "Player 11 should move."  # safe fallback, not a silently-wrong number


def test_translate_from_english_protects_percentages_and_coordinates():
    def _echo_llm(prompt: str, **kwargs):
        assert "3.1" not in prompt and "52.0" not in prompt
        return "Tăng @@0@@ tại vị trí @@1@@.", 10

    result = translate_from_english(
        "Gain of +3.1% at position 52.0.", "Vietnamese", llm_call=_echo_llm
    )
    assert result == "Tăng +3.1% tại vị trí 52.0."


def test_translate_from_english_llm_failure_falls_back_to_original():
    def _failing_llm(prompt: str, **kwargs):
        raise RuntimeError("rate limited")

    result = translate_from_english("Pass to player 8.", "Vietnamese", llm_call=_failing_llm)
    assert result == "Pass to player 8."


def test_translate_from_english_empty_text():
    result = translate_from_english("", "Vietnamese")
    assert result == ""


def test_mentioned_player_mismatch_detects_different_player():
    """Reproduces the reported confusion: user asks about player 11 while the
    sidebar is still on player 1 — the mismatch must be detectable so the
    dashboard can warn instead of silently answering about the wrong player."""
    assert mentioned_player_mismatch("What should player 11 do in this situation?", 1) == 11


def test_mentioned_player_mismatch_none_when_same_player():
    assert mentioned_player_mismatch("What should player 1 do?", 1) is None


def test_mentioned_player_mismatch_none_when_no_player_mentioned():
    assert mentioned_player_mismatch("What is the best tactical option right now?", 1) is None


def test_mentioned_player_mismatch_handles_hash_and_case_variants():
    assert mentioned_player_mismatch("what should Player #11 do?", 1) == 11
    assert mentioned_player_mismatch("PLAYER 11 should press", 1) == 11
